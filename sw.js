self.addEventListener('install', e => {
  self.skipWaiting();
  // descarga todo de una vez; si algún archivo falla, guarda el resto igualmente
  e.waitUntil(caches.open(CACHE).then(c => Promise.all(ARCHIVOS.map(a => c.add(new Request(a, { cache: 'reload' })).catch(() => {})))));
});
self.addEventListener('activate', e => e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET' || !e.request.url.startsWith(self.location.origin)) return;
  const url = new URL(e.request.url);
  const imagen = /\.(webp|png|jpe?g|mp3|ogg|wav)$/i.test(url.pathname);
  if (imagen) {
    // imágenes y sonidos: primero lo guardado (rápido y sin red)
    e.respondWith(caches.match(e.request).then(r => r || fetch(e.request).then(n => { const c = n.clone(); caches.open(CACHE).then(k => k.put(e.request, c)); return n; })));
  } else {
    // código y página: primero internet (para tener lo último), si no hay, lo guardado
    e.respondWith(fetch(e.request).then(n => { const c = n.clone(); caches.open(CACHE).then(k => k.put(e.request, c)); return n; })
      .catch(() => caches.match(e.request, { ignoreSearch: true }).then(r => r || caches.match('./'))));
  }
});
